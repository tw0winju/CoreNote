// ── 문서 요약 ─────────────────────────────────────────────────────────────────
export const summaryPrompt = (text) =>
  `아래는 문서 전체 내용이다.

당신의 작업은 "요약"이 아니라 "학습용 정리본 작성"이다.

핵심 목표:

* 시험 공부와 복습이 가능하도록 원문의 정보를 최대한 보존한다.
* 정보 보존을 최우선으로 하며 길어지는 것은 허용하지만 정보 누락은 허용하지 않는다.

내용 규칙:

1. 문서의 모든 장, 절, 소제목을 포함한다.
2. 주요 개념, 정의, 특징, 절차, 장단점, 비교 항목을 모두 포함한다.
3. 중요 수치, 공식, 용어, 예시, 표 내용을 유지한다.
4. 내용을 임의로 축약하거나 생략하지 않는다.
5. 새로운 정보를 추가하거나 추론하지 않는다.
6. "등", "기타", "여러 가지"와 같이 내용을 뭉뚱그리지 않는다.
7. 하나의 bullet에 여러 개념을 합치지 않는다.
8. 원문에 등장한 개념 수와 정리본의 개념 수가 최대한 일치해야 한다.
9. 출력 분량은 원문의 최소 50% 이상을 목표로 한다.

출력 형식:

* Markdown 사용
* 대제목: ##
* 소제목: ###
* 모든 내용은 bullet(-) 형태로 정리
* 정의 → 특징 → 예시 순으로 작성
* 비교 항목은 표 형태로 정리
* 서론, 결론, 부가 설명 없이 정리본만 출력
* <think> 태그 출력 금지

중요:
현재 출력이 지나치게 압축되어 있다.
각 개념을 가능한 한 세분화하여 작성하라.
하나의 bullet은 하나의 개념만 설명해야 한다.
개념 개수 > 요약 길이
원문에 등장한 개념이 100개라면 정리본에도 최대한 100개 수준의 개별 항목이 존재해야 한다.

만약 한 문장으로 요약할 수 있다고 판단되더라도 요약하지 말고,
원문에 등장한 세부 개념들을 분리하여 각각 독립 항목으로 작성하라.

---
${text}
---`;

